// Runs in the avro-untrusted-classes surefire execution, where no package is trusted
public class AvroTrustedClassesTest {

  public static class Order {
    public int id = 7;
    public List<Line> lines = new ArrayList<>();
    public Status status = Status.OPEN;
    public Address address = new Address();
  }

  public static class Line {
    public int qty = 2;
  }

  public enum Status { OPEN, CLOSED }

  // Implements SpecificRecord, like generated code, but is not generated
  public static class Generated extends SpecificRecordBase {
    @Override
    public Schema getSchema() {
      return null;
    }

    @Override
    public Object get(int field) {
      return null;
    }

    @Override
    public void put(int field, Object value) {
    }
  }

  // Marked as generated by Avro, as generated code is
  @AvroGenerated
  public static class Annotated {
  }


  @BeforeClass
  public static void requireUntrustedFork() {
    assumeTrue(Boolean.getBoolean("avro.untrusted.classes"));
  }

  @Before
  @After
  public void reset() {
    AvroTrustedClasses.resetToDefaults();
  }

  // A fresh ReflectData, since Avro caches the classes each instance has loaded
  private static Order roundTrip(Order order) throws IOException {
    ReflectData data = new ReflectData();
    Schema schema = data.getSchema(Order.class);
    ByteArrayOutputStream out = new ByteArrayOutputStream();
    BinaryEncoder encoder = EncoderFactory.get().binaryEncoder(out, null);
    new ReflectDatumWriter<Order>(schema, data).write(order, encoder);
    encoder.flush();
    return new ReflectDatumReader<Order>(schema, schema, data)
        .read(null, DecoderFactory.get().binaryDecoder(out.toByteArray(), null));
  }

  private static Order order() {
    Order order = new Order();
    order.lines.add(new Line());
    return order;
  }

  @Test
  public void untrustedPojoIsRejectedByAvro() {
    assertThrows(SecurityException.class, () -> roundTrip(order()));
  }

  @Test
  public void trustCoversTheObjectGraph() throws IOException {
    AvroTrustedClasses.trust(Order.class);
    Order result = roundTrip(order());
    assertEquals(2, result.lines.get(0).qty);
    assertEquals("Springfield", result.address.city);
    // Nested types under their binary names, and a type in another package
    assertTrue(AvroTrustedClasses.isTrusted(Line.class));
    assertTrue(AvroTrustedClasses.isTrusted(Status.class));
    assertTrue(AvroTrustedClasses.isTrusted(Address.class));
  }

  @Test
  public void trustExactlyDoesNotFollowReferencedTypes() {
    AvroTrustedClasses.trustExactly(Order.class);
    assertTrue(AvroTrustedClasses.isTrusted(Order.class));
    assertFalse(AvroTrustedClasses.isTrusted(Line.class));
  }

  @Test
  public void trustClassOfTrustsAnApplicationValue() throws IOException {
    AvroTrustedClasses.trustClassOf(order());
    assertEquals(2, roundTrip(order()).lines.get(0).qty);
  }

  @Test
  public void trustClassOfIgnoresGenericRecords() {
    // A generic record's schema may name any class; that must not make the class trusted
    Schema schema = ReflectData.get().getSchema(Line.class);
    AvroTrustedClasses.trustClassOf(new GenericData.Record(schema));
    assertFalse(AvroTrustedClasses.isTrusted(Line.class));
  }

  // A container that is not a generated class, like the serializer's NonRecordContainer
  public static class Container implements GenericContainer {
    @Override
    public Schema getSchema() {
      return ReflectData.get().getSchema(Line.class);
    }
  }

  // POJOs that reflection derives a schema for, although they are a number and a map
  public static class Money extends Number {
    public long cents = 100;

    @Override
    public int intValue() {
      return (int) cents;
    }

    @Override
    public long longValue() {
      return cents;
    }

    @Override
    public float floatValue() {
      return cents;
    }

    @Override
    public double doubleValue() {
      return cents;
    }
  }

  public static class Attributes extends HashMap<String, String> {
  }

  @Test
  public void trustClassOfTrustsNumberAndMapPojos() {
    AvroTrustedClasses.trustClassOf(new Money());
    AvroTrustedClasses.trustClassOf(new Attributes());
    assertTrue(AvroTrustedClasses.isTrusted(Money.class));
    assertTrue(AvroTrustedClasses.isTrusted(Attributes.class));
    // Primitive values are left alone
    AvroTrustedClasses.trustClassOf(new StringBuilder("s"));
    assertFalse(AvroTrustedClasses.isTrusted(StringBuilder.class));
  }

  // Hand-written specific records without SCHEMA$, so their schema is not derivable from the class
  public static class HandWrittenChild extends SpecificRecordBase {
    static final Schema SCHEMA = SchemaBuilder.record("HandWrittenChild")
        .namespace(AvroTrustedClassesTest.class.getName()).fields().requiredInt("x").endRecord();

    @Override
    public Schema getSchema() {
      return SCHEMA;
    }

    @Override
    public Object get(int field) {
      return null;
    }

    @Override
    public void put(int field, Object value) {
    }
  }

  public static class HandWritten extends SpecificRecordBase {
    static final Schema SCHEMA = SchemaBuilder.record("HandWritten")
        .namespace(AvroTrustedClassesTest.class.getName()).fields()
        .name("child").type(HandWrittenChild.SCHEMA).noDefault().endRecord();

    @Override
    public Schema getSchema() {
      return SCHEMA;
    }

    @Override
    public Object get(int field) {
      return null;
    }

    @Override
    public void put(int field, Object value) {
    }
  }

  @Test
  public void trustClassOfTrustsSpecificRecordsInAMap() {
    AvroTrustedClasses.trustClassOf(Collections.singletonMap("k", new HandWritten()));
    assertTrue(AvroTrustedClasses.isTrusted(HandWritten.class));
    assertTrue(AvroTrustedClasses.isTrusted(HandWrittenChild.class));
  }

  // A hand-written record whose instances report a schema other than their class's, as if taken
  // from the registry
  public static class Dynamic extends SpecificRecordBase {
    public static final Schema SCHEMA$ = SchemaBuilder.record("Dynamic")
        .namespace(AvroTrustedClassesTest.class.getName()).fields().endRecord();

    @Override
    public Schema getSchema() {
      return SchemaBuilder.record("Dynamic").namespace(AvroTrustedClassesTest.class.getName())
          .fields().name("line").type(ReflectData.get().getSchema(Line.class)).noDefault()
          .endRecord();
    }

    @Override
    public Object get(int field) {
      return null;
    }

    @Override
    public void put(int field, Object value) {
    }
  }

  @Test
  public void trustClassOfPrefersTheClassSchema() {
    AvroTrustedClasses.trustClassOf(new Dynamic());
    assertTrue(AvroTrustedClasses.isTrusted(Dynamic.class));
    assertFalse(AvroTrustedClasses.isTrusted(Line.class));
  }

  @Test
  public void trustClassOfIgnoresGenericRecordsInAMap() {
    Schema schema = ReflectData.get().getSchema(Line.class);
    AvroTrustedClasses.trustClassOf(
        Collections.singletonMap("k", new GenericData.Record(schema)));
    assertFalse(AvroTrustedClasses.isTrusted(Line.class));
  }

  @Test
  public void trustClassOfTrustsPojosInCollections() {
    AvroTrustedClasses.trustClassOf(Collections.singletonList(new Line()));
    assertTrue(AvroTrustedClasses.isTrusted(Line.class));
    // Through nesting, as a map of lists
    AvroTrustedClasses.trustClassOf(
        Collections.singletonMap("k", Collections.singletonList(new Child())));
    assertTrue(AvroTrustedClasses.isTrusted(Child.class));
  }

  @Test
  public void trustClassOfIgnoresGenericRecordsInACollection() {
    Schema schema = ReflectData.get().getSchema(Line.class);
    AvroTrustedClasses.trustClassOf(
        Collections.singletonList(new GenericData.Record(schema)));
    assertFalse(AvroTrustedClasses.isTrusted(Line.class));
  }

  @Test
  public void trustClassOfHandlesAMapThatContainsItself() {
    Map<String, Object> map = new HashMap<>();
    map.put("self", map);
    AvroTrustedClasses.trustClassOf(map);
  }

  public static class Child {
    public int x = 1;
  }

  public static class Parent {
    @AvroDefault("null")
    public Child child;
  }

  @Test
  public void trustClassOfWalksPojosThatNeedAllowNull() {
    // Plain reflection rejects a null default for a record field
    assertThrows(RuntimeException.class, () -> ReflectData.get().getSchema(Parent.class));
    AvroTrustedClasses.trustClassOf(new Parent());
    assertTrue(AvroTrustedClasses.isTrusted(Child.class));
  }

  @Test
  public void trustClassOfIgnoresOtherContainers() {
    AvroTrustedClasses.trustClassOf(new Container());
    assertFalse(AvroTrustedClasses.isTrusted(Container.class));
    assertFalse(AvroTrustedClasses.isTrusted(Line.class));
  }

  @Test
  public void classesGeneratedByAvroAreTrustedByDefault() {
    assertTrue(AvroTrustedClasses.isTrusted(Annotated.class));
    // Avro loads it through the installed validator
    Schema schema = SchemaBuilder.record("Annotated")
        .namespace(AvroTrustedClassesTest.class.getName()).fields().endRecord();
    assertEquals(Annotated.class, new SpecificData().getClass(schema));
    // Implementing SpecificRecord does not make a class generated
    assertFalse(AvroTrustedClasses.isTrusted(Generated.class));
  }

  @Test
  public void trustPackagesIgnoresATrailingDot() {
    AvroTrustedClasses.trustPackages("io.confluent.kafka.schemaregistry.avro.othermodel.");
    assertTrue(AvroTrustedClasses.isTrusted(Address.class));
  }

  @Test
  public void trustPackagesMatchesWholePackagesAndSubpackages() {
    AvroTrustedClasses.trustPackages("io.confluent.kafka.schemaregistry.avro.other");
    assertFalse(AvroTrustedClasses.isTrusted(Address.class));
    AvroTrustedClasses.trustPackages("io.confluent.kafka.schemaregistry");
    assertTrue(AvroTrustedClasses.isTrusted(Address.class));
    // A nested class reports its enclosing package
    assertTrue(AvroTrustedClasses.isTrusted(Line.class));
  }

  @Test
  public void trustClassesUsesBinaryNames() {
    AvroTrustedClasses.trustClasses(Line.class.getName());
    assertTrue(AvroTrustedClasses.isTrusted(Line.class));
    assertFalse(AvroTrustedClasses.isTrusted(Order.class));
  }

  @Test
  public void trustAllPackages() throws IOException {
    AvroTrustedClasses.trustPackages("*");
    assertEquals(2, roundTrip(order()).lines.get(0).qty);
  }

  @Test
  public void trustPredicate() {
    AvroTrustedClasses.trust(clazz -> clazz == Line.class);
    assertTrue(AvroTrustedClasses.isTrusted(Line.class));
    assertFalse(AvroTrustedClasses.isTrusted(Order.class));
  }

  @Test
  public void collectionTypesAreTrustedByDefault() {
    assertTrue(AvroTrustedClasses.isTrusted(ArrayList.class));
    assertTrue(AvroTrustedClasses.isTrusted(List.class));
    assertFalse(AvroTrustedClasses.isTrusted(Order.class));
  }

  @Test
  public void installsOnTopOfAReplacedValidator() {
    ClassSecurityPredicate original = ClassSecurityValidator.getGlobal();
    try {
      ClassSecurityValidator.setGlobal(ClassSecurityValidator.builder().add(Line.class).build());
      assertFalse(AvroTrustedClasses.isInstalled());
      AvroTrustedClasses.trustExactly(Order.class);
      assertTrue(AvroTrustedClasses.isInstalled());
      // The replacing validator's trust is kept
      assertTrue(ClassSecurityValidator.getGlobal().isTrusted(Line.class));
      assertTrue(ClassSecurityValidator.getGlobal().isTrusted(Order.class));
    } finally {
      ClassSecurityValidator.setGlobal(original);
    }
  }

  @Test
  public void resetToDefaultsDropsDeclarations() {
    AvroTrustedClasses.trust(Order.class);
    AvroTrustedClasses.resetToDefaults();
    assertFalse(AvroTrustedClasses.isTrusted(Order.class));
    assertTrue(AvroTrustedClasses.isInstalled());
  }
}
