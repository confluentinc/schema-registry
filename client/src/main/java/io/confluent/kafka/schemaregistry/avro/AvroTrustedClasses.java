package io.confluent.kafka.schemaregistry.avro;

import com.google.common.cache.Cache;
import com.google.common.cache.CacheBuilder;
import java.nio.ByteBuffer;
import java.util.Arrays;
import java.util.Collection;
import java.util.Collections;
import java.util.HashSet;
import java.util.IdentityHashMap;
import java.util.List;
import java.util.Map;
import java.util.Set;
import java.util.concurrent.ConcurrentHashMap;
import java.util.function.Predicate;
import org.apache.avro.Schema;
import org.apache.avro.generic.GenericContainer;
import org.apache.avro.reflect.ReflectData;
import org.apache.avro.specific.AvroGenerated;
import org.apache.avro.specific.SpecificData;
import org.apache.avro.specific.SpecificFixed;
import org.apache.avro.specific.SpecificRecord;
import org.apache.avro.util.ClassSecurityValidator;
import org.apache.avro.util.ClassSecurityValidator.ClassSecurityPredicate;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;

/**
 * Declares the classes that Avro may load. Avro 1.12.2 (AVRO-4189) only loads a class that a
 * JVM-wide validator trusts. This adds a validator, on top of whatever is installed, that trusts
 * every class generated by Avro (annotated with {@link AvroGenerated}), whose construction runs no
 * application code, and the classes declared here. Declaring a class also trusts the types Avro
 * resolves from the schema it derives for it: nested records, enums and fixed types, and the
 * classes named by its java-class properties. Any other class named only by a schema is not
 * trusted implicitly.
 *
 * <p>On an Avro without the validator, every method is a no-op.
 */
public final class AvroTrustedClasses {

  private static final Logger log = LoggerFactory.getLogger(AvroTrustedClasses.class);

  // Collection types that reflection records as java-class properties on the schemas it derives
  private static final List<String> DEFAULT_CLASSES = Arrays.asList(
      "java.util.Collection",
      "java.util.List",
      "java.util.ArrayList",
      "java.util.Set",
      "java.util.HashSet",
      "java.util.LinkedHashSet",
      "java.util.TreeSet",
      "java.util.Map",
      "java.util.HashMap",
      "java.util.LinkedHashMap",
      "java.util.TreeMap",
      "java.util.concurrent.ConcurrentHashMap");

  private static final String ALL_PACKAGES = "*";

  // Values whose schema AvroSchemaUtils.getSchema derives without reflection
  private static final List<Class<?>> NON_REFLECTIVE_TYPES = Arrays.asList(
      Boolean.class, Integer.class, Long.class, Float.class, Double.class, CharSequence.class,
      byte[].class, ByteBuffer.class);

  private static final boolean VALIDATOR_AVAILABLE = isValidatorAvailable();

  private static volatile State state = new State();

  private AvroTrustedClasses() {
  }

  private static boolean isValidatorAvailable() {
    try {
      Class.forName("org.apache.avro.util.ClassSecurityValidator", false,
          AvroTrustedClasses.class.getClassLoader());
      return true;
    } catch (ClassNotFoundException | LinkageError e) {
      return false;
    }
  }

  private static final class State {
    private final Set<String> classes = ConcurrentHashMap.newKeySet();
    private final Set<String> packages = ConcurrentHashMap.newKeySet();
    private final Set<Predicate<Class<?>>> predicates = ConcurrentHashMap.newKeySet();
    private volatile boolean allPackages;
    // Classes already walked, so that trusting the class of every serialized value is cheap
    private final Cache<Class<?>, Boolean> walked = CacheBuilder.newBuilder().weakKeys().build();

    private State() {
      classes.addAll(DEFAULT_CLASSES);
    }

    private boolean isTrusted(Class<?> clazz) {
      // Reading an annotation does not initialize the class
      if (allPackages || classes.contains(clazz.getName())
          || clazz.isAnnotationPresent(AvroGenerated.class)) {
        return true;
      }
      // A nested class reports its enclosing package
      Package classPackage = clazz.getPackage();
      if (classPackage != null && isTrustedPackage(classPackage.getName())) {
        return true;
      }
      for (Predicate<Class<?>> predicate : predicates) {
        if (predicate.test(clazz)) {
          return true;
        }
      }
      return false;
    }

    private boolean isTrustedPackage(String packageName) {
      for (String trusted : packages) {
        // Trusting "com.example.model" also trusts its subpackages, but not "com.example.modelx"
        if (packageName.startsWith(trusted) && (packageName.length() == trusted.length()
            || packageName.charAt(trusted.length()) == '.')) {
          return true;
        }
      }
      return false;
    }
  }

  /**
   * Trusts the given classes and the types Avro resolves from the schemas it derives for them.
   */
  public static void trust(Class<?>... classes) {
    State current = state;
    for (Class<?> clazz : classes) {
      if (clazz != null) {
        current.classes.add(clazz.getName());
        current.classes.addAll(typesReachableFrom(clazz));
      }
    }
    install();
  }

  /**
   * Trusts every class that the given predicate accepts.
   */
  public static void trust(Predicate<Class<?>> predicate) {
    if (predicate != null) {
      state.predicates.add(predicate);
      install();
    }
  }

  /**
   * Trusts the given classes only, not the types they reference.
   */
  public static void trustExactly(Class<?>... classes) {
    State current = state;
    for (Class<?> clazz : classes) {
      if (clazz != null) {
        current.classes.add(clazz.getName());
      }
    }
    install();
  }

  /**
   * Trusts the classes with the given binary names, such as {@code com.example.Outer$Inner}.
   */
  public static void trustClasses(String... classNames) {
    trustClasses(Arrays.asList(classNames));
  }

  public static void trustClasses(Collection<String> classNames) {
    State current = state;
    for (String className : classNames) {
      if (className != null && !className.trim().isEmpty()) {
        current.classes.add(className.trim());
      }
    }
    install();
  }

  /**
   * Trusts every class in the given packages and their subpackages. The package {@code *} trusts
   * every class, which turns off Avro's check.
   */
  public static void trustPackages(String... packageNames) {
    trustPackages(Arrays.asList(packageNames));
  }

  public static void trustPackages(Collection<String> packageNames) {
    State current = state;
    for (String packageName : packageNames) {
      if (packageName == null || packageName.trim().isEmpty()) {
        continue;
      }
      if (ALL_PACKAGES.equals(packageName.trim())) {
        if (!current.allPackages) {
          log.warn("Trusting every class for Avro deserialization, which disables the check "
              + "added by AVRO-4189");
        }
        current.allPackages = true;
      } else {
        // As in Avro's own SERIALIZABLE_PACKAGES, "com.example." means "com.example"
        String trusted = packageName.trim();
        current.packages.add(trusted.endsWith(".")
            ? trusted.substring(0, trusted.length() - 1) : trusted);
      }
    }
    install();
  }

  /**
   * Trusts the class of a value the application serializes, if Avro resolves it reflectively,
   * as for a specific record or a reflect POJO. Generic records, enums and fixed values and
   * primitive values are left alone, since their schema, not their class, names their types.
   */
  public static void trustClassOf(Object value) {
    if (!VALIDATOR_AVAILABLE || value == null) {
      return;
    }
    if (value instanceof Map) {
      // Only maps are traversed, so only they need cycle protection
      trustClassOf(value, Collections.newSetFromMap(new IdentityHashMap<>()));
    } else {
      trustOwnClass(value);
    }
  }

  private static void trustClassOf(Object value, Set<Object> visited) {
    if (value == null || !visited.add(value)) {
      return;
    }
    if (value instanceof Map) {
      // As in AvroSchemaUtils.getSchema, a map's schema comes from its first value
      Map<?, ?> map = (Map<?, ?>) value;
      if (!map.isEmpty()) {
        trustClassOf(map.values().iterator().next(), visited);
      }
    }
    trustOwnClass(value);
  }

  private static void trustOwnClass(Object value) {
    if (!isResolvedReflectively(value)) {
      return;
    }
    Class<?> clazz = value.getClass();
    State current = state;
    if (current.walked.getIfPresent(clazz) == null) {
      current.classes.add(clazz.getName());
      Schema schema = deriveSchema(clazz);
      if (schema == null && value instanceof GenericContainer) {
        // A hand-written specific record may have no schema derivable from its class
        schema = ((GenericContainer) value).getSchema();
      }
      if (schema != null) {
        current.classes.addAll(typesReachableFrom(schema, clazz.getClassLoader()));
      }
      current.walked.put(clazz, Boolean.TRUE);
      install();
    }
  }

  private static boolean isResolvedReflectively(Object value) {
    if (value instanceof GenericContainer) {
      // Of the containers, only generated specific classes are loaded by name
      return value instanceof SpecificRecord || value instanceof SpecificFixed
          || value instanceof Enum;
    }
    for (Class<?> type : NON_REFLECTIVE_TYPES) {
      if (type.isInstance(value)) {
        return false;
      }
    }
    return true;
  }

  /**
   * Whether this helper's validator is the one Avro uses, which is false on an Avro without the
   * validator and until something is declared.
   */
  public static boolean isInstalled() {
    return VALIDATOR_AVAILABLE && Validator.isInstalled();
  }

  /**
   * Drops every declaration, keeping only the default collection types.
   */
  public static void resetToDefaults() {
    state = new State();
    install();
  }

  // Exposed for tests
  static boolean isTrusted(Class<?> clazz) {
    return state.isTrusted(clazz);
  }

  /**
   * Installs this helper's validator, which trusts every class generated by Avro even when nothing
   * else is declared.
   */
  public static void install() {
    if (VALIDATOR_AVAILABLE) {
      Validator.install();
      AvroSchemaUtils.clearUntrustedSchemas();
    }
  }

  // Only loaded when Avro has the validator, so that the rest of this class works without it.
  // Avro's global validator field is not volatile, so the first declaration should happen before
  // other threads use Avro, as it does when a serializer or deserializer is configured.
  private static final class Validator {
    private static final ClassSecurityPredicate TRUSTED = clazz -> state.isTrusted(clazz);

    private static ClassSecurityPredicate installed;

    private Validator() {
    }

    static synchronized void install() {
      ClassSecurityPredicate current = ClassSecurityValidator.getGlobal();
      if (current != installed) {
        // Keep whatever is installed, such as Avro's defaults and system properties
        installed = ClassSecurityValidator.composite(current, TRUSTED);
        ClassSecurityValidator.setGlobal(installed);
      }
    }

    static synchronized boolean isInstalled() {
      return installed != null && ClassSecurityValidator.getGlobal() == installed;
    }
  }

  // Deriving the schema uses plain reflection and never consults the validator
  private static Set<String> typesReachableFrom(Class<?> clazz) {
    Schema schema = deriveSchema(clazz);
    return schema != null
        ? typesReachableFrom(schema, clazz.getClassLoader())
        : Collections.emptySet();
  }

  private static Set<String> typesReachableFrom(Schema schema, ClassLoader loader) {
    Set<String> names = new HashSet<>();
    collectTypeNames(schema, Collections.newSetFromMap(new IdentityHashMap<>()), names, loader);
    return names;
  }

  private static Schema deriveSchema(Class<?> clazz) {
    try {
      return ReflectData.get().getSchema(clazz);
    } catch (RuntimeException e) {
      try {
        // Such as a POJO whose null defaults only avro.reflection.allow.null supports
        return ReflectData.AllowNull.get().getSchema(clazz);
      } catch (RuntimeException e2) {
        // Not every class has a derivable schema, such as an interface; the class is still trusted
        log.debug("Could not derive an Avro schema for {}", clazz.getName(), e);
        return null;
      }
    }
  }

  private static void collectTypeNames(Schema schema, Set<Schema> visited, Set<String> names,
      ClassLoader loader) {
    if (schema == null || !visited.add(schema)) {
      return;
    }
    // Collection and stringable types are recorded as properties naming the declared class
    addIfPresent(schema.getProp(SpecificData.CLASS_PROP), names);
    addIfPresent(schema.getProp(SpecificData.KEY_CLASS_PROP), names);
    addIfPresent(schema.getProp(SpecificData.ELEMENT_PROP), names);
    switch (schema.getType()) {
      case RECORD:
        addNamedType(schema, names, loader);
        for (Schema.Field field : schema.getFields()) {
          collectTypeNames(field.schema(), visited, names, loader);
        }
        break;
      case ENUM:
      case FIXED:
        addNamedType(schema, names, loader);
        break;
      case ARRAY:
        collectTypeNames(schema.getElementType(), visited, names, loader);
        break;
      case MAP:
        collectTypeNames(schema.getValueType(), visited, names, loader);
        break;
      case UNION:
        for (Schema member : schema.getTypes()) {
          collectTypeNames(member, visited, names, loader);
        }
        break;
      default:
        break;
    }
  }

  // Avro writes a nested class as a.b.Outer.Inner but loads it as a.b.Outer$Inner, and the
  // validator matches the loaded name
  private static void addNamedType(Schema schema, Set<String> names, ClassLoader loader) {
    String fullName = schema.getFullName();
    if (fullName != null) {
      Class<?> resolved = resolveClass(fullName, loader != null ? loader : defaultClassLoader());
      names.add(resolved != null ? resolved.getName() : fullName);
    }
  }

  private static ClassLoader defaultClassLoader() {
    ClassLoader loader = Thread.currentThread().getContextClassLoader();
    return loader != null ? loader : AvroTrustedClasses.class.getClassLoader();
  }

  // Mirrors SpecificData.getClass, without initializing the class or consulting the validator
  private static Class<?> resolveClass(String fullName, ClassLoader loader) {
    Class<?> resolved = loadClass(fullName, loader);
    if (resolved != null) {
      return resolved;
    }
    StringBuilder candidate = new StringBuilder(fullName);
    int lastDot = fullName.lastIndexOf('.');
    while (lastDot != -1) {
      candidate.setCharAt(lastDot, '$');
      resolved = loadClass(candidate.toString(), loader);
      if (resolved != null) {
        return resolved;
      }
      lastDot = fullName.lastIndexOf('.', lastDot - 1);
    }
    return null;
  }

  private static Class<?> loadClass(String name, ClassLoader loader) {
    try {
      return Class.forName(name, false, loader);
    } catch (ClassNotFoundException | LinkageError e) {
      return null;
    }
  }

  private static void addIfPresent(String className, Set<String> names) {
    if (className != null && !className.isEmpty()) {
      names.add(className);
    }
  }
}
